  const [savedCv] = await rows<{file_id: string; kind: string}>(sql`SELECT file_id,kind FROM hirelix_private_records WHERE user_id=${owner}::uuid AND id=${String(cvCreated.results[0].result!.record_id)}::uuid`);
  assert.deepEqual(savedCv, {file_id: resume.id, kind: "cv"});
  const invalidCv = await saveFile(owner, {name: "table.csv", type: "text/csv", bytes: Buffer.from("not a CV")});
