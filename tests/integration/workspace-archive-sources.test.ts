const database = new URL(process.env.DATABASE_URL || "postgres://invalid/invalid");
assert.ok(["localhost", "127.0.0.1"].includes(database.hostname) && database.port !== "15432" && database.pathname.startsWith("/hirelix_workspace_qa_coldstart_"));
const owners: string[] = [];
after(async () => {
  for (const owner of owners) await db.execute(sql`UPDATE hirelix_private_jobs SET status='cancelled' WHERE user_id=${owner}::uuid AND status IN ('queued','running')`);
  await closeDb();
});
type ToolResult<T> = {ok:boolean; result:T; error?:{code:number;message:string}};

test("archive sources are paged, owned, authorized and attached with exact provenance", async () => {
  const owner = randomUUID(), other = randomUUID();
  owners.push(owner, other);
  const original = "A".repeat(100010) + "\nHistorical note from 2022-04-11.";
  const archive = zipSync({"notes/communication.txt":strToU8(original), "candidates.csv":strToU8("Name\nExample Person\n")});
  const file = await uploadConversationFile(owner, {name:"history.zip",type:"application/zip",bytes:archive});
  const person = await createPerson(owner, {name:"Example Person",email:"example@example.test"});
  const instruction = "Save this historical candidate note from the archive.";
  const sent = await sendMessage(owner, {message:instruction,request_key:randomUUID(),file_ids:[file.id]});
  const job = await claimJob(["chat"], {id:sent.job.id,userId:owner}); assert.ok(job);
  const conversation = await conversationDetails(owner,sent.conversation_id);
  const question = conversation.messages.find(message => message.role === "user")!;
  const tools = createAgentTools({job,conversation:conversation.conversation,question,messages:[],document:null,attachments:[],locale:"en",timezone:"UTC",signal:new AbortController().signal,progress:async()=>{},sources:new Map(),clarification:null});
  const read = tools.read_file as unknown as {execute:(input:unknown,options:{toolCallId:string})=>Promise<ToolResult<{text:string;next_offset:number|null;archive_path:string|null}>>};
  const save = tools.save_record as unknown as {execute:(input:unknown,options:{toolCallId:string})=>Promise<ToolResult<{record:{id:string}}>>};
  const first = await read.execute({file_id:file.id,archive_path:"notes/communication.txt"},{toolCallId:"read-1"});
  assert.equal(first.ok,true); assert.equal(first.result.text.length,100000); assert.equal(first.result.next_offset,100000);
  const second = await read.execute({file_id:file.id,archive_path:"notes/communication.txt",offset:first.result.next_offset},{toolCallId:"read-2"});
  assert.equal(second.ok,true); assert.match(second.result.text,/Historical note from 2022-04-11/); assert.equal(second.result.next_offset,null);
  const foreign = await uploadConversationFile(other, {name:"foreign.zip",type:"application/zip",bytes:archive});
  assert.equal((await read.execute({file_id:foreign.id,archive_path:"notes/communication.txt"},{toolCallId:"foreign"})).error?.code,404);
  const input = {authorization_quote:instruction,person_id:person.id,role_id:null,record:{kind:"note",title:"Historical note",content:"Historical note from 2022-04-11.",occurred_at:null,occurred_on:"2022-04-11"},file_id:file.id,archive_path:"notes/communication.txt"};
  assert.equal((await save.execute({...input,authorization_quote:"not authorized"},{toolCallId:"denied"})).error?.code,403);
  const result = await save.execute(input,{toolCallId:"save"}); assert.equal(result.ok,true);
  const repeated = await save.execute(input,{toolCallId:"repeat"}); assert.equal(repeated.result.record.id,result.result.record.id);
  const [record] = await rows<{file_id:string;details:Record<string,unknown>}>(sql`SELECT file_id,details FROM hirelix_private_records WHERE user_id=${owner}::uuid AND id=${result.result.record.id}::uuid`);
  assert.equal(record.details.source_archive_file_id,file.id); assert.equal(record.details.source_archive_path,"notes/communication.txt");
  assert.equal(record.details.occurred_on,"2022-04-11");
  assert.equal((await readFile(owner,record.file_id)).bytes.toString(),original);
  const count = await rows(sql`SELECT id FROM hirelix_private_records WHERE user_id=${owner}::uuid AND person_id=${person.id}::uuid AND title='Historical note'`);
  assert.equal(count.length,1);
  await finishJob(job,{result:{tested:true}});
});
